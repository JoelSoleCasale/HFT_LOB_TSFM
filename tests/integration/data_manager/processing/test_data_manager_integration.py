    def test_data_validation_with_real_data(self, temp_data_cache):
        """Test data validation and consistency with real sample data."""
        cache_root, sample_date = temp_data_cache

        processor = OrderBookProcessor(cache_root)

        request = OrderBookSnapshotRequest(
            exchange="binance_futures",
            symbol="BTCUSDT",
            date=sample_date,
            levels=5,
            batch_size=10_000,
        )

        result = processor.generate_full_event_sampled(request)

        # Test data consistency
        df = result.df

        # Timestamps should be unique (no duplicates after deduplication)
        assert df["timestamp"].is_duplicated().sum() == 0

        # Ask prices should be >= bid prices at each level
        for i in range(1, 6):
            ask_col = f"ask{i}_price"
            bid_col = f"bid{i}_price"

            # Filter out null values for comparison
            valid_rows = df.filter(pl.col(ask_col).is_not_null() & pl.col(bid_col).is_not_null())

            if len(valid_rows) > 0:
                # Ask prices should generally be higher than bid prices
                spread_check = valid_rows.select(
                    (pl.col(ask_col) >= pl.col(bid_col)).alias("valid_spread")
                )
                valid_spread_ratio = spread_check["valid_spread"].mean()
                assert valid_spread_ratio > 0.8, f"Most spreads should be positive for level {i}"

        # Quantities should be positive when not null
        for i in range(1, 6):
            ask_qty_col = f"ask{i}_qty"
            bid_qty_col = f"bid{i}_qty"

            ask_qtys = df[ask_qty_col].drop_nulls()
            bid_qtys = df[bid_qty_col].drop_nulls()

            if len(ask_qtys) > 0:
                assert ask_qtys.min() > 0, f"Ask quantities should be positive for level {i}"
            if len(bid_qtys) > 0:
                assert bid_qtys.min() > 0, f"Bid quantities should be positive for level {i}"

