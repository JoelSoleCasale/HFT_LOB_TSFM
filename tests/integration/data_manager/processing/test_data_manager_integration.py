    def test_generate_full_event_sampled_orderbook_depth_consistency(self, temp_synthetic_cache):
        """Test that orderbook depth is maintained consistently."""
        cache_root, test_date = temp_synthetic_cache

        processor = OrderBookProcessor(cache_root)

        request = OrderBookSnapshotRequest(
            exchange="test_exchange",
            symbol="BTCUSDT",
            date=test_date,
            levels=4,  # Request more levels than we sometimes have
            reference_ts="received_time",
            batch_size=1000,
            ob_init_prev_day_rows=0,
        )

        result = processor.generate_full_event_sampled(request)
        df = result.df

        # Check that when we don't have enough levels, the remaining are NaN
        for row_dict in df.to_dicts():
            # Count non-null bid and ask levels
            bid_levels = sum(1 for i in range(1, 5) if row_dict.get(f"bid{i}_price") is not None)
            ask_levels = sum(1 for i in range(1, 5) if row_dict.get(f"ask{i}_price") is not None)

            # Should have at least 1 level, but might not have all 4
            assert bid_levels >= 1, f"Should have at least 1 bid level, got {bid_levels}"
            assert ask_levels >= 1, f"Should have at least 1 ask level, got {ask_levels}"

            # Bid prices should be decreasing, ask prices should be increasing
            bid_prices = [row_dict.get(f"bid{i}_price") for i in range(1, bid_levels + 1)]
            ask_prices = [row_dict.get(f"ask{i}_price") for i in range(1, ask_levels + 1)]

            # Filter out None values
            valid_bid_prices = [p for p in bid_prices if p is not None]
            valid_ask_prices = [p for p in ask_prices if p is not None]

            if len(valid_bid_prices) > 1:
                assert valid_bid_prices == sorted(
                    valid_bid_prices, reverse=True
                ), "Bid prices should be decreasing"
            if len(valid_ask_prices) > 1:
                assert valid_ask_prices == sorted(
                    valid_ask_prices
                ), "Ask prices should be increasing"

