def assert_hftbacktest_matches_sampler(
    df_ob: pl.DataFrame,
    cache_root,
    exchange: str,
    symbol: str,
    date: date,
    levels: int,
    delta: int = 100_000_000,
    skip_hft_rows: int = 2,
    skip_sampler_rows: int = 1,
    verbose: bool = True,
):
    """
    Compare orderbook snapshots generated by hftbacktest and IncrementalOrderBookSampler.
    Raises AssertionError if they do not match within tolerance.
    """
    from polars.testing import assert_frame_equal
    from hftbacktest import BacktestAsset, HashMapMarketDepthBacktest
    from utils import get_hftbacktest_array
    from numba import njit

    @njit
    def _get_ob_sampled_njit(hbt, delta: int, levels: int):
        capacity = 100_000
        timestamps = np.empty(capacity, dtype=np.int64)
        ask_prices = np.full((capacity, levels), np.nan, dtype=np.float64)
        ask_qtys = np.full((capacity, levels), np.nan, dtype=np.float64)
        bid_prices = np.full((capacity, levels), np.nan, dtype=np.float64)
        bid_qtys = np.full((capacity, levels), np.nan, dtype=np.float64)
        row_num = 0
        while hbt.elapse(delta - hbt.current_timestamp % delta) == 0:
            if row_num >= capacity:
                new_capacity = capacity * 2
                new_timestamps = np.empty(new_capacity, dtype=np.int64)
                new_timestamps[:capacity] = timestamps
                timestamps = new_timestamps
                new_ask_prices = np.full((new_capacity, levels), np.nan, dtype=np.float64)
                new_ask_prices[:capacity] = ask_prices
                ask_prices = new_ask_prices
                new_ask_qtys = np.full((new_capacity, levels), np.nan, dtype=np.float64)
                new_ask_qtys[:capacity] = ask_qtys
                ask_qtys = new_ask_qtys
                new_bid_prices = np.full((new_capacity, levels), np.nan, dtype=np.float64)
                new_bid_prices[:capacity] = bid_prices
                bid_prices = new_bid_prices
                new_bid_qtys = np.full((new_capacity, levels), np.nan, dtype=np.float64)
                new_bid_qtys[:capacity] = bid_qtys
                bid_qtys = new_bid_qtys
                capacity = new_capacity
            depth = hbt.depth(0)
            timestamps[row_num] = hbt.current_timestamp
            _extract_orderbook_levels(
                depth, levels, ask_prices, ask_qtys, bid_prices, bid_qtys, row_num
            )
            row_num += 1
        return (
            timestamps[:row_num],
            ask_prices[:row_num],
            ask_qtys[:row_num],
            bid_prices[:row_num],
            bid_qtys[:row_num],
        )

    @njit
    def _extract_orderbook_levels(
        depth, levels, ask_prices, ask_qtys, bid_prices, bid_qtys, row_num
    ):
        tick_size = depth.tick_size
        lvl = 0
        if depth.best_ask_tick > 0:
            for tick_price in range(depth.best_ask_tick, depth.best_ask_tick + 10_000):
                qty = depth.ask_qty_at_tick(tick_price)
                if qty > 0:
                    ask_prices[row_num, lvl] = tick_price * tick_size
                    ask_qtys[row_num, lvl] = qty
                    lvl += 1
                    if lvl == levels:
                        break
        lvl = 0
        if depth.best_bid_tick > 0:
            for tick_price in range(depth.best_bid_tick, max(depth.best_bid_tick - 10_000, 0), -1):
                qty = depth.bid_qty_at_tick(tick_price)
                if qty > 0:
                    bid_prices[row_num, lvl] = tick_price * tick_size
                    bid_qtys[row_num, lvl] = qty
                    lvl += 1
                    if lvl == levels:
                        break

    def get_ob_sampled(hbt, delta: int, levels: int) -> np.ndarray:
        timestamps, ask_prices, ask_qtys, bid_prices, bid_qtys = _get_ob_sampled_njit(
            hbt, delta, levels
        )
        dtype = [("timestamp", "i8")]
        dtype.extend(
            [
                (f"{s}{i}_{t}", "f8")
                for i in range(1, levels + 1)
                for s in ["ask", "bid"]
                for t in ["price", "qty"]
            ]
        )
        num_rows = len(timestamps)
        structured_array = np.empty(num_rows, dtype=dtype)
        structured_array["timestamp"] = timestamps
        for i in range(levels):
            structured_array[f"ask{i+1}_price"] = ask_prices[:, i]
            structured_array[f"ask{i+1}_qty"] = ask_qtys[:, i]
            structured_array[f"bid{i+1}_price"] = bid_prices[:, i]
            structured_array[f"bid{i+1}_qty"] = bid_qtys[:, i]
        return structured_array

    # Generate data using hftbacktest approach
    hft_array = get_hftbacktest_array(df_ob, target_time_unit="ms")
    asset = (
        BacktestAsset()
        .data([hft_array])
        .linear_asset(1.0)
        .risk_adverse_queue_model()
        .no_partial_fill_exchange()
        .trading_value_fee_model(0.0002, 0.0007)
        .tick_size(0.1)
        .lot_size(0.001)
    )
    hbt = HashMapMarketDepthBacktest([asset])
    sampled_ob_hft = pl.DataFrame(get_ob_sampled(hbt, delta=delta, levels=levels))
    hbt.close()

    sampler = IncrementalOrderBookSampler(cache_root)
    ob_sampled = sampler.get_orderbook(
        exchange=exchange,
        symbol=symbol,
        date=date,
        levels=levels,
    ).sample_by_time(time_delta=delta, interpolate=True)
    sampled_ob_incremental = ob_sampled.df.select(sampled_ob_hft.columns)

    # Compare the two approaches (skip first few rows as hftbacktest may have different initialization)
    df1 = sampled_ob_hft[skip_hft_rows:]
    df2 = (
        sampled_ob_incremental[:-skip_sampler_rows]
        if skip_sampler_rows > 0
        else sampled_ob_incremental
    )

    assert len(df1) > 0, "hftbacktest sampled data should not be empty"
    assert len(df2) > 0, "incremental sampler data should not be empty"

    # Align lengths for fair comparison
    if len(df1) != len(df2):
        min_len = min(len(df1), len(df2))
        df1 = df1[:min_len]
        df2 = df2[:min_len]
        if verbose:
            print(f"Adjusted to common length: {min_len}")

    if verbose:
        print(f"HFT length: {len(df1)}, Incremental length: {len(df2)}")
        if len(df1) > 5:
            print("First 3 rows comparison:")
            print("HFT:", df1.head(3))
            print("Incremental:", df2.head(3))

    try:
        assert_frame_equal(df1.drop("timestamp"), df2.drop("timestamp"), abs_tol=0.0001)
    except AssertionError as e:
        print(f"Exact match failed: {e}")
        assert df1.shape == df2.shape, "DataFrames should have same shape"
        assert df1.columns == df2.columns, "DataFrames should have same columns"
        # Instead of requiring timestamps to be identical, check that they are close (within delta)
        ts1 = df1["timestamp"].to_numpy()
        ts2 = df2["timestamp"].to_numpy()
        max_diff = np.max(np.abs(ts1 - ts2))
        assert (
            max_diff <= delta
        ), f"Timestamps should be within delta ({delta}): max diff {max_diff}"
        for col in df1.columns:
            if "price" in col:
                vals1 = df1[col].drop_nulls()
                vals2 = df2[col].drop_nulls()
                if len(vals1) > 0 and len(vals2) > 0:
                    mean1 = vals1.mean()
                    mean2 = vals2.mean()
                    rel_diff = (
                        abs(mean1 - mean2) / max(mean1, mean2) if max(mean1, mean2) > 0 else 0
                    )
                    assert (
                        rel_diff < 0.01
                    ), f"Mean prices for {col} should be within 1%: {mean1} vs {mean2}"
        print("Structural similarity test passed - data patterns are consistent")


